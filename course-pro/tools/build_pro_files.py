            ("הרחבות $", exp_, NUM, "=SUMIFS('לקוחות'!E:E,'לקוחות'!D:D,\"הרחבה\")"),
            ("צמצומים $ (חיובי)", con, NUM, "=-SUMIFS('לקוחות'!E:E,'לקוחות'!D:D,\"צמצום\")"),
            ("נטישה $ (חיובי)", churn, NUM, "=-SUMIFS('לקוחות'!E:E,'לקוחות'!D:D,\"נטישה\")"),
            ("ARR סגירה $", sum(e for _, _, e in cust), NUM, "=SUM('לקוחות'!C2:C26)"),
