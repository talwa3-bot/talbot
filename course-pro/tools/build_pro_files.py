def check(ws, ref, expected, at, tol=1.0):
    """תא בדיקה מיידית ליד התשובה."""
    if isinstance(expected, str):
        f = f'=IF({ref}="","",IF(TRIM({ref})="{expected}","✓ נכון","✗ עוד לא"))'
    else:
        f = f'=IF({ref}="","",IF(ABS({ref}-({expected}))<={tol},"✓ נכון","✗ עוד לא"))'
    ws[at] = f
    ws[at].font = Font(bold=True)
    ws.conditional_formatting.add(at, FormulaRule(formula=[f'LEFT({at},1)="✓"'], fill=OK_FILL))
    ws.conditional_formatting.add(at, FormulaRule(formula=[f'LEFT({at},1)="✗"'], fill=NO_FILL))


def qa(ws, top, rows, solution, col_w=(62, 18, 16)):
    """טבלת שאלות: שאלה | תשובה | בדיקה. rows = [(שאלה, ערך נכון, פורמט, נוסחת פתרון או None)]"""
    for j, h in enumerate(["שאלה", "התשובה שלך", "בדיקה"]):
        c = ws.cell(row=top, column=1 + j, value=h)
        c.fill, c.font = HEAD_FILL, HEAD_FONT
    for i, (q, exp, fmt, f) in enumerate(rows, start=top + 1):
        ws.cell(row=i, column=1, value=q).alignment = Alignment(wrap_text=True, vertical="top")
        c = ws.cell(row=i, column=2, value=(f if (solution and f) else (exp if solution else None)))
        c.number_format = fmt or NUM
        c.fill = SOL_FILL if solution else INPUT_FILL
        check(ws, f"B{i}", exp, f"C{i}", tol={PCT: 0.005, "0.00": 0.005, "0.0": 0.05, "0": 0.1}.get(fmt, 1.0))
    for k, w in enumerate(col_w):
        ws.column_dimensions["ABC"[k]].width = w
    return top + len(rows)


