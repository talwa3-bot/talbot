def build_tech_saas():
    import random
    rnd = random.Random(606)
    cust = []
    for k in range(25):
        start = rnd.choice([0, 0, 0] + [rnd.randint(40, 900) * 1000 for _ in range(10)])
        if start == 0:
            end = rnd.randint(60, 400) * 1000
        else:
            roll = rnd.random()
            end = 0 if roll < 0.12 else int(start * rnd.choice([0.8, 0.9, 1.0, 1.0, 1.15, 1.3, 1.5]) / 1000) * 1000
        cust.append((f"CUS-{101 + k}", start, end))

    def cls(s, e):
        if s == 0:
            return "חדש"
        if e == 0:
            return "נטישה"
        if e > s:
            return "הרחבה"
        if e < s:
            return "צמצום"
        return "ללא שינוי"

    agg = {}
    for _, s, e in cust:
        c = cls(s, e)
        agg[c] = agg.get(c, 0) + (e - s)
    start_arr = sum(s for _, s, _ in cust)
    new, exp_, con, churn = agg.get("חדש", 0), agg.get("הרחבה", 0), -agg.get("צמצום", 0), -agg.get("נטישה", 0)
    nrr = (start_arr + exp_ - con - churn) / start_arr
    grr = (start_arr - con - churn) / start_arr
    sm = 2_400_000  # החלק מהוצאות השיווק והמכירה שמיוחס לרכישת לקוחות חדשים
    payback = sm / (new * 0.78) * 12
    for sol in (False, True):
        wb = Workbook()
        ws = new_sheet(wb, "הוראות", first=True)
